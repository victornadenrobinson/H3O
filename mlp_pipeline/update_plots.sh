#!/bin/bash
# Refresh the pwidom / hull results and figures from whatever has finished (login node, no GPU, safe while scans are still running: their Python code is already loaded).
#   1. pwidom_scan --status: which hosts are still missing
#   2. --rescore every runs/pwidom*/ folder (robust pressure correction; old table kept as scan.jsonl.bak)
#   3. one merged table of all scans -> docs/data/pwidom_scan_latest.csv (derived numbers only: safe to commit)
#   4. mu / hull figure of the three methods -> runs/mu_hull_methods.png (and docs/figures/mu_hull_methods.png with COMMIT=1)
# usage (repo root):  bash mlp_pipeline/update_plots.sh          COMMIT=1 bash mlp_pipeline/update_plots.sh   (also commits + pushes the csv and the figure)
[ -d mlp_pipeline ] || { echo "run from the repo root"; exit 2; }
PY=${PY:-$HOME/grace-venv/bin/python}
echo "== 1. status"; $PY mlp_pipeline/tdi/pwidom_scan.py --status 'runs/pwidom*' | grep -E "^runs|MISSING" || true
echo; echo "== 2. rescore (robust pressure correction)"
for d in runs/pwidom*/; do [ -n "$(ls $d/pw_*_K*.json 2>/dev/null)" ] && $PY mlp_pipeline/tdi/pwidom_scan.py --rescore ${d%/} | tail -n 1; done
echo; echo "== 3. merged table -> docs/data/pwidom_scan_latest.csv"
$PY - <<'PYEOF'
import glob, json, os
rows = {}
for f in sorted(glob.glob("runs/pwidom*/scan.jsonl"), key=os.path.getmtime):
    for l in open(f):
        r = json.loads(l); fl = r["flags"]
        flag = "melted" if "MELTED" in fl else ("unconverged" if ("UNCONVERGED" in fl or "few effective" in fl) else "ok")
        key = (r["P"], r["T"], round(r.get("n", 0.0), 4))
        old = rows.get(key)
        if old is None or (old["flag"] != "ok" and flag == "ok") or (old["flag"] == flag and r["err"] < old["err_meV"]):   # prefer converged, then the smaller error
            rows[key] = dict(P_GPa=r["P"], T_K=r["T"], n=round(r.get("n", 0.0), 4), dg_meV=round(r["dg"], 1), err_meV=round(r["err"], 1),
                             widom_minus_deletion_meV=round(r.get("widom", 0) - r.get("deletion", 0), 1), kish=round(r["kish"], 3), flag=flag, src=os.path.dirname(f))
with open("docs/data/pwidom_scan_latest.csv", "w") as fh:
    fh.write("# pwidom (proxy Widom / deletion + BAR) next-H cost dg = mu_H(host) - G_H, robust pressure correction, merged over runs/pwidom*/ (best row per P, T, n). Generated by update_plots.sh\n")
    fh.write("P_GPa,T_K,n,dg_meV,err_meV,widom_minus_deletion_meV,kish,flag,src\n")
    for k in sorted(rows): fh.write(",".join(str(rows[k][c]) for c in ("P_GPa", "T_K", "n", "dg_meV", "err_meV", "widom_minus_deletion_meV", "kish", "flag", "src")) + "\n")
print(f"{len(rows)} (P, T, n) rows; per (P, T):")
for PT in sorted({k[:2] for k in rows}):
    pts = sorted((k[2], rows[k]) for k in rows if k[:2] == PT)
    print(f"   {PT[0]:5.0f} GPa {PT[1]:5.0f} K: " + "  ".join(f"n={n:.3f} {r['dg_meV']:+.0f}{'' if r['flag'] == 'ok' else '*'}" for n, r in pts))
print("   (* = unconverged or melted)")
PYEOF
echo; echo "== 4. figure"; $PY mlp_pipeline/tdi/fig_methods.py -o runs/mu_hull_methods.png
if [ -n "$COMMIT" ]; then
  cp runs/mu_hull_methods.png docs/figures/mu_hull_methods.png
  git add docs/data/pwidom_scan_latest.csv docs/figures/mu_hull_methods.png && git commit -m "pwidom scan results and mu / hull figure updated ($(date +%F))" && git pull --no-rebase --no-edit origin claude/eloquent-hopper-kfjdei && git push origin HEAD:claude/eloquent-hopper-kfjdei
fi
echo "done: runs/mu_hull_methods.png, docs/data/pwidom_scan_latest.csv"
